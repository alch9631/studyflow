import "./testDb";
import assert from "node:assert/strict";
import { prisma } from "./db";
import { addFocusNoteForUser, focusNotesForUser, updateFocusNoteForUser } from "./focusNotes";
import { rebuildSchedule, todayISO } from "./planService";
import { finishFocusForUser, startFocusForUser } from "./focusSession";
import { sessionLength } from "./sessionLength";

async function main() {
  for (const value of ["0", "601", "1.5", "-3", "", "25min", "Infinity", null, 25]) assert.equal(sessionLength(value), undefined);
  for (const value of ["1", "2", "25", "600"]) assert.equal(sessionLength(value), Number(value));
  const user = await prisma.user.create({ data: { email: "journal@example.test" } });
  const other = await prisma.user.create({ data: { email: "journal-other@example.test" } });
  const exam = new Date(todayISO() + "T00:00:00Z"); exam.setUTCDate(exam.getUTCDate() + 10);
  const course = await prisma.course.create({ data: { userId: user.id, name: "Algebra", examDate: exam, studyDays: "0,1,2,3,4,5,6" } });
  const topic = await prisma.topic.create({ data: { courseId: course.id, title: "Matrices", note: { create: { body: "Original scratchpad" } } } });
  const input = { topicId: topic.id, id: "note-one", body: "  First observation\nA second line  " };
  assert.equal((await addFocusNoteForUser(other.id, input)).ok, false);
  assert.deepEqual(await focusNotesForUser(other.id, topic.id), []);
  const first = await addFocusNoteForUser(user.id, input); assert.ok(first.ok);
  assert.equal(first.note.body, "First observation\nA second line");
  await addFocusNoteForUser(user.id, input);
  assert.equal(await prisma.focusNote.count({ where: { topicId: topic.id } }), 1, "a retry registers the note once");
  const changedRetry = await addFocusNoteForUser(user.id, { ...input, body: "Different body" }); assert.ok(changedRetry.ok);
  assert.equal(changedRetry.note.body, first.note.body, "a repeated create cannot overwrite an edited entry");
  const edit = { ...input, body: "Edited observation", updatedAt: first.note.updatedAt };
  assert.equal((await updateFocusNoteForUser(other.id, edit)).ok, false);
  const updated = await updateFocusNoteForUser(user.id, edit); assert.ok(updated.ok);
  assert.notEqual(updated.note.updatedAt, first.note.updatedAt, "edits receive a new revision even within one millisecond");
  const conflict = await updateFocusNoteForUser(user.id, { ...edit, body: "Old tab" });
  assert.equal(conflict.ok, false); if (!conflict.ok) assert.equal(conflict.reason, "conflict");
  assert.equal((await prisma.focusNote.findUniqueOrThrow({ where: { id: input.id } })).body, "Edited observation");
  await assert.rejects(() => addFocusNoteForUser(user.id, { ...input, id: "blank", body: " \n " }));
  await assert.rejects(() => addFocusNoteForUser(user.id, { ...input, id: "too-long", body: "x".repeat(4001) }));
  await assert.rejects(() => addFocusNoteForUser(user.id, { ...input, id: "topic:fake" }));
  const another = await prisma.topic.create({ data: { courseId: course.id, title: "Another" } });
  assert.equal((await addFocusNoteForUser(user.id, { ...input, topicId: another.id })).ok, false, "an ID cannot move a note to a different topic");
  assert.equal((await updateFocusNoteForUser(user.id, { ...edit, topicId: another.id })).ok, false);
  let list = await focusNotesForUser(user.id, topic.id);
  const legacy = list.find((note) => note.id.startsWith("topic:")); assert.ok(legacy);
  const legacyEdit = await updateFocusNoteForUser(user.id, { ...legacy, topicId: topic.id, body: "Updated original notes" });
  assert.ok(legacyEdit.ok);
  assert.equal((await prisma.note.findUniqueOrThrow({ where: { topicId: topic.id } })).body, "Updated original notes", "original course notes stay editable and synchronized");
  await rebuildSchedule(user.id);
  assert.equal((await focusNotesForUser(user.id, topic.id)).length, 2, "replanning preserves both entries");
  const started = await startFocusForUser(user.id, { courseId: course.id, topicId: topic.id, language: "en" }); assert.ok(started);
  await finishFocusForUser(user.id, { blockId: started.blockId, topicId: topic.id, elapsedSeconds: 60, response: "A note from the earlier timer" });
  list = await focusNotesForUser(user.id, topic.id);
  assert.equal(list.length, 3, "earlier timer notes remain available without a backfill or a GET write");
  const session = list.find((note) => note.id.startsWith("session:")); assert.ok(session);
  const completed = await prisma.studyBlock.findFirstOrThrow({ where: { courseId: course.id, completed: true } });
  const before = JSON.parse(completed.studyResult!);
  assert.ok((await updateFocusNoteForUser(user.id, { ...session, topicId: topic.id, body: "Edited earlier timer note" })).ok);
  const after = JSON.parse((await prisma.studyBlock.findUniqueOrThrow({ where: { id: completed.id } })).studyResult!);
  for (const key of ["outcome", "checked", "plannedMinutes", "requestId", "planUpdated", "recordedAt"]) assert.equal(after[key], before[key], `editing notes preserves ${key}`);
  assert.equal(after.response, "Edited earlier timer note");
  assert.equal((await prisma.studyBlock.findUniqueOrThrow({ where: { id: completed.id } })).actualMinutes, completed.actualMinutes);
  await prisma.topic.update({ where: { id: topic.id }, data: { done: true } });
  assert.ok((await updateFocusNoteForUser(user.id, { ...updated.note, topicId: topic.id, body: "Still editable after completion" })).ok);
  const limited = await prisma.topic.create({ data: { courseId: course.id, title: "Limit" } });
  await prisma.focusNote.createMany({ data: Array.from({ length: 500 }, (_, index) => ({ id: `limit-${index}`, topicId: limited.id, body: "Saved" })) });
  const limit = await addFocusNoteForUser(user.id, { ...input, topicId: limited.id, id: "over-limit" });
  assert.equal(limit.ok, false); if (!limit.ok) assert.equal(limit.reason, "limit");
  await prisma.course.delete({ where: { id: course.id } });
  assert.equal(await prisma.focusNote.count(), 0, "explicit course deletion still removes its notes");
  console.log("Focus note checks passed: persistence, retries, edits, stale revisions, ownership, legacy notes, replanning, completion, limits and duration validation.");
}
main().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => prisma.$disconnect());
