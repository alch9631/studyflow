import "./testDb";
import assert from "node:assert/strict";
import { prisma } from "./db";
import { startFocusForUser, finishFocusForUser } from "./focusSession";
import { readStudyResult, readStudyTask, quickStudyTask } from "./studyTask";
import { saveStudyCheckpoint } from "./practicalStudy";
import { calibrationFromHistory } from "./planService";
import { summarizeLearning } from "./learningEvidence";

async function main() {
  const user = await prisma.user.create({ data: { email: "timer@example.test" } });
  const other = await prisma.user.create({ data: { email: "other@example.test" } });
  const course = await prisma.course.create({ data: { userId: user.id, name: "Algebra", examDate: new Date("2030-01-01"), studyDays: "" } });
  const topic = await prisma.topic.create({ data: { courseId: course.id, title: "Matrices", note: { create: { body: "Original course notes" } } } });
  const input = { courseId: course.id, topicId: topic.id, language: "en" as const };
  assert.equal(await startFocusForUser(other.id, input), null, "foreign course cannot start");
  assert.equal(await startFocusForUser(user.id, { ...input, topicId: "missing" }), null, "missing topic does not silently start another");
  const started = await startFocusForUser(user.id, input);
  assert.ok(started, "no material, setup or study days are required");
  const again = await startFocusForUser(user.id, input);
  assert.equal(again?.blockId, started.blockId, "double start reuses the session");
  let block = await prisma.studyBlock.findUniqueOrThrow({ where: { id: started.blockId } });
  assert.equal(block.minutes, 30);
  assert.equal((await prisma.topic.findUniqueOrThrow({ where: { id: topic.id } })).studyTask, null, "starting does not fabricate instructions");
  await saveStudyCheckpoint(user.id, { blockId: block.id, topicId: topic.id, response: "my notes", elapsedSeconds: 125, sessionMinutes: 30, updatedAt: new Date().toISOString() });
  const finish = { blockId: block.id, topicId: topic.id, elapsedSeconds: 125, response: "my notes" };
  assert.equal(await finishFocusForUser(other.id, finish), null, "foreign completion rejected");
  assert.equal(await finishFocusForUser(user.id, { ...finish, topicId: "missing" }), null, "mismatched topic rejected");
  await assert.rejects(() => finishFocusForUser(user.id, { ...finish, elapsedSeconds: -1 }));
  await finishFocusForUser(user.id, finish);
  await finishFocusForUser(user.id, { ...finish, elapsedSeconds: 300 });
  block = await prisma.studyBlock.findUniqueOrThrow({ where: { id: block.id } });
  assert.equal(block.completed, true);
  assert.equal(block.actualMinutes, 2, "retry never credits time twice");
  assert.equal(block.minutes, 3, "ending early only credits the minutes studied, rounded up");
  assert.equal(readStudyResult(block.studyResult)?.outcome, "session", "session is not a passed check");
  assert.equal(readStudyResult(block.studyResult)?.response, "my notes", "work survives finishing");
  const saved = await prisma.topic.findUniqueOrThrow({ where: { id: topic.id }, include: { note: true } });
  assert.equal(saved.studyProgress, null);
  assert.equal(saved.done, false, "elapsed time does not prove mastery");
  assert.equal(saved.note?.body, "Original course notes", "original notes are not overwritten");
  assert.equal(await saveStudyCheckpoint(user.id, { blockId: block.id, topicId: topic.id, response: "late save", elapsedSeconds: 125, updatedAt: new Date().toISOString() }), null, "late autosave cannot resurrect completed work");
  assert.equal(calibrationFromHistory([block]), 1, "early timer finishes do not distort task estimates");
  assert.equal(summarizeLearning([block]).attempts, 0, "timer sessions are not counted as knowledge checks");
  assert.equal(summarizeLearning([{ ...block, studyResult: JSON.stringify({ version: 1, outcome: "complete", recordedAt: "2020-01-01T00:00:00Z" }) }, block]).goalsMet, 1, "timer sessions do not erase earlier learning evidence");
  const next = await startFocusForUser(user.id, input);
  assert.ok(next && next.blockId !== block.id, "next session gets a fresh clock");
  assert.equal(await finishFocusForUser(user.id, { ...finish, blockId: "stale-id" }), null, "stale requests cannot finish new sessions");
  await prisma.topic.update({ where: { id: topic.id }, data: { studyTask: JSON.stringify(quickStudyTask("read", 15, "en", {})) } });
  await finishFocusForUser(user.id, { ...finish, blockId: next.blockId });
  assert.equal((await prisma.topic.findUniqueOrThrow({ where: { id: topic.id } })).done, false, "prepared tasks also finish without claiming a checked goal");
  const file = await prisma.moduleFile.create({ data: { courseId: course.id, filename: "scanned.pdf", mimeType: "application/pdf", content: Buffer.from("unreadable"), sizeBytes: 10 } });
  const material = await startFocusForUser(user.id, { courseId: course.id, fileId: file.id, language: "en" });
  assert.ok(material, "an unreadable PDF never blocks the timer");
  const materialBlock = await prisma.studyBlock.findUniqueOrThrow({ where: { id: material.blockId } });
  const materialTopic = await prisma.topic.findUniqueOrThrow({ where: { id: materialBlock.topicId } });
  assert.equal(readStudyTask(materialTopic.studyTask)?.sourceFileId, file.id, "original material link is retained");
  assert.equal(await startFocusForUser(other.id, { courseId: course.id, fileId: file.id, language: "en" }), null);
  console.log("Focus session checks passed: direct starts, defaults, ownership, notes, completion, retries, stale saves and unreadable materials.");
}
main().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => prisma.$disconnect());
